// Accuracy evaluation on synthetic routes with KNOWN ground truth.
// Run:  npm run eval        (writes docs/EVALUATION.md, deterministic seeds)
import { writeFileSync } from 'node:fs';
import {
  reconstruct, detectArcs, generateSyntheticRoute, pipeWidthInUnits,
  SAMPLE_TRUE_ROUTE, buildCurveRoute
} from '../js/algorithm.js';

const TRIALS = 50;
const MATCH_TOL_FT = 15; // a true bend counts as "found" if a reconstructed vertex lies within this

// tiny seeded RNG for outlier placement (separate from the generator's own)
function rng(seed) {
  return () => { seed |= 0; seed = (seed + 0x6D2B79F5) | 0; let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t; return ((t ^ (t >>> 14)) >>> 0) / 4294967296; };
}
const mean = a => a.reduce((s, x) => s + x, 0) / a.length;
const median = a => { const b = [...a].sort((x, y) => x - y); return b[Math.floor(b.length / 2)]; };
const pct = (n, d) => (100 * n / d).toFixed(0) + '%';
const dist = (p, q) => Math.hypot(p.x - q.x, p.y - q.y);

function scoreVertices(trueVerts, vertices) {
  const errs = trueVerts.map(t => Math.min(...vertices.map(v => dist(t, v))));
  const interior = errs.slice(1, -1);
  return { meanErr: mean(errs), missed: interior.filter(e => e > MATCH_TOL_FT).length, interiorN: interior.length, flags: interior.map(e => e > MATCH_TOL_FT) };
}

function cornerTrial({ widthIn, noise, outliers = 0, seed }) {
  const raw = generateSyntheticRoute(SAMPLE_TRUE_ROUTE, 25, noise, seed, 100, 0.01);
  if (outliers) {
    const r = rng(seed * 7919);
    const used = new Set();
    while (used.size < outliers) used.add(1 + Math.floor(r() * (raw.length - 2)));
    for (const i of used) { const a = r() * 2 * Math.PI; raw[i] = { ...raw[i], x: raw[i].x + 15 * Math.cos(a), y: raw[i].y + 15 * Math.sin(a) }; }
  }
  const res = reconstruct(raw, pipeWidthInUnits(widthIn, 'ft'), 10, 5);
  const sc = scoreVertices(SAMPLE_TRUE_ROUTE, res.vertices);
  return { exact: res.vertices.length === SAMPLE_TRUE_ROUTE.length, extra: res.vertices.length - SAMPLE_TRUE_ROUTE.length, ...sc, outliersDropped: res.outlierCount };
}

function summarize(rows) {
  return {
    exact: pct(rows.filter(r => r.exact).length, rows.length),
    meanErr: mean(rows.map(r => r.meanErr)).toFixed(2),
    missed: pct(rows.reduce((s, r) => s + r.missed, 0), rows.reduce((s, r) => s + r.interiorN, 0)),
    extra: mean(rows.map(r => r.extra)).toFixed(2),
    dropped: mean(rows.map(r => r.outliersDropped)).toFixed(1)
  };
}

const out = [];
const w = s => out.push(s);

w('# Accuracy evaluation\n');
w('Generated by `npm run eval` (`eval/evaluate.js`). Every trial uses a synthetic route with **known ground truth**, so errors are measured against the true vertices rather than eyeballed. Seeds are fixed, so the numbers are reproducible.\n');
w(`**Setup.** ${TRIALS} random seeds per cell. Shots every 25 ft, each displaced sideways by uniform noise of ±*amplitude* (the "crew meander" model in \`generateSyntheticRoute\`). Reconstruction uses the app defaults (bend threshold 10°, min points per segment 5). The route is the app's sample route: 5 true vertices, 3 of them real bends (90°, 38°, 90°; run lengths 480, 260, 420 and 300 ft). A true bend counts as *found* if a reconstructed vertex lies within ${MATCH_TOL_FT} ft of it.\n`);

w('## 1. Noise and pipe width\n');
w('| Pipe width | Noise ± (ft) | Exactly 5 vertices | Mean vertex error (ft) | Bends missed | Mean extra vertices |');
w('|---|---|---|---|---|---|');
const missByWidth = {};
for (const widthIn of [8, 24, 36]) {
  missByWidth[widthIn] = [0, 0, 0]; let trials = 0;
  for (const noise of [0.5, 1.5, 3, 5]) {
    const rows = []; for (let s = 1; s <= TRIALS; s++) rows.push(cornerTrial({ widthIn, noise, seed: s }));
    rows.forEach(r => r.flags.forEach((f, i) => { if (f) missByWidth[widthIn][i]++; })); trials += rows.length;
    const r = summarize(rows);
    w(`| ${widthIn}" | ${noise} | ${r.exact} | ${r.meanErr} | ${r.missed} | ${r.extra} |`);
  }
  missByWidth[widthIn].trials = trials;
}

w('\n**Which bends get missed?** Share of trials (all four noise levels pooled) in which each true bend had no reconstructed vertex within ' + MATCH_TOL_FT + ' ft. Bend A (90°) and bend B (38°) bracket the shortest straight run in the route (260 ft, about 10 shots); bend C (90°) comes after a long 420 ft run.\n');
w('| Pipe width | Bend A | Bend B | Bend C |');
w('|---|---|---|---|');
for (const widthIn of [8, 24, 36]) {
  const m = missByWidth[widthIn];
  w(`| ${widthIn}" | ${pct(m[0], m.trials)} | ${pct(m[1], m.trials)} | ${pct(m[2], m.trials)} |`);
}
w('\nA correct vertex *count* does not guarantee correct geometry: when a short run is absorbed into a neighbour, a spurious vertex elsewhere can keep the total at 5. That is why the table reports missed bends separately.');

w('\n## 2. Gross outliers (single bad shots 15 ft off)\n');
w('Noise ±1.5 ft. "Dropped" is the mean number of shots the MAD outlier check removed per run (injected outliers are a subset of what it may drop; it can also drop ordinary noisy shots).\n');
w('| Pipe width | Outliers injected | Exactly 5 vertices | Mean vertex error (ft) | Bends missed | Mean shots dropped |');
w('|---|---|---|---|---|---|');
for (const widthIn of [8, 24]) for (const outliers of [0, 1, 3, 5]) {
  const rows = []; for (let s = 1; s <= TRIALS; s++) rows.push(cornerTrial({ widthIn, noise: 1.5, outliers, seed: s }));
  const r = summarize(rows);
  w(`| ${widthIn}" | ${outliers} | ${r.exact} | ${r.meanErr} | ${r.missed} | ${r.dropped} |`);
}

w('\n## 3. Arc detection on a curved route\n');
w('Route: 250 ft straight, a true circular sweep of 90° at **R = 400 ft**, 250 ft straight. Shots every 10 ft, 8" pipe, bend threshold 3°, min points 3, arc detection on. "Line + arc + line" is the ideal outcome. Radius error is measured on the runs that produced exactly one arc.\n');
w('| Noise ± (ft) | Line + arc + line | Any arc found | Median radius error | Worst radius error |');
w('|---|---|---|---|---|');
const curve = buildCurveRoute(400, 90, 7.5, 250);
for (const noise of [0.5, 1, 2]) {
  let ideal = 0, any = 0; const errs = [];
  for (let s = 1; s <= TRIALS; s++) {
    const raw = generateSyntheticRoute(curve, 10, noise, s, 100, 0.01);
    const els = detectArcs(reconstruct(raw, pipeWidthInUnits(8, 'ft'), 3, 3));
    const arcs = els.filter(e => e.type === 'arc');
    if (arcs.length) any++;
    if (els.map(e => e.type[0]).join('') === 'lal') ideal++;
    if (arcs.length === 1) errs.push(Math.abs(arcs[0].radius - 400) / 400);
  }
  w(`| ${noise} | ${pct(ideal, TRIALS)} | ${pct(any, TRIALS)} | ${errs.length ? (100 * median(errs)).toFixed(1) + '%' : 'n/a'} | ${errs.length ? (100 * Math.max(...errs)).toFixed(0) + '%' : 'n/a'} |`);
}

w('\n## Caveats\n');
w('- **Synthetic data only.** The noise model is uniform sideways displacement; real crews also have systematic offsets, instrument error and non-uniform spacing. Treat these numbers as a controlled comparison, not a field accuracy claim.');
w('- The route has a single geometry. Different bend angles and run lengths will shift the numbers.');
w('- Parameters are the app defaults (or the curve-demo settings) with no per-trial tuning.');

writeFileSync(new URL('../docs/EVALUATION.md', import.meta.url), out.join('\n') + '\n');
console.log(out.join('\n'));
